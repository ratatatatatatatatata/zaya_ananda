export type Scene = "gobi" | "mountain" | "monastery" | "forest" | "steppe" | "lake";

export type JourneyDay = {
  label: string;
  title: string;
  text: string;
  bullets?: string[];
  image?: string;
  scene: Scene;
};

export type Person = {
  name: string;
  role: string;
  info: string;
  image?: string;
};

export type Journey = {
  id: string;
  slug: string;
  name: string;
  tagline: string;
  scene: Scene;
  image?: string;
  days: string;
  /** Хамтдаа явах дээд хэмжээ, жишээ: "Дээд тал нь 15 хүн" */
  groupSize: string;
  transport: string;
  stay: string;
  audience: string;
  summary: string;
  included: string;
  excluded: string;
  price: string;
  /** Урьдчилгаа төлбөр (₮). 0 бол урьдчилгаа авахгүй. */
  prepay?: number;
  itinerary: JourneyDay[];
  /** Аяллыг хариуцан удирдах хүн */
  lead: Person;
  /** Хамт явах баг */
  crew: Person[];
  createdAt: string;
};

