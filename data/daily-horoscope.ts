/** Огноо + ордоос тогтмол индекс гаргах (тухайн өдөрт өөрчлөгдөхгүй) */
export function pickIndex(seedKey: string, dateKey: string, len: number): number {
  const s = seedKey + "|" + dateKey;
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h) % len;
}

/** Өдрийн эрчмийн оноо (1–5 од) — орд, огнооноос тогтмол */
export function energyScore(zodiacKey: string, dateKey: string, salt: string): number {
  return 2 + (pickIndex(zodiacKey + salt, dateKey, 4)); // 2..5
}
