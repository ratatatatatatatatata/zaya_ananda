export function zodiacOf(month: number, day: number): Zodiac {
  for (const z of ZODIAC_SIGNS) {
    const [fm, fd] = z.from, [tm, td] = z.to;
    if (fm <= tm) {
      if ((month === fm && day >= fd) || (month === tm && day <= td) || (month > fm && month < tm)) return z;
    } else {
      if ((month === fm && day >= fd) || (month === tm && day <= td) || month > fm || month < tm) return z;
    }
  }
  return ZODIAC_SIGNS[0];
}

