export function lifePathOf(y: number, m: number, d: number): number {
  const sum = (n: number): number => String(n).split("").reduce((a, c) => a + Number(c), 0);
  let t = sum(y) + sum(m) + sum(d);
  while (t > 9 && t !== 11 && t !== 22) t = sum(t);
  return t;
}

